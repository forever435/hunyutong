function getFilteredServices() {
    const typeFilter = document.getElementById('serviceType').value;
    const sortMethod = document.getElementById('sortType').value;
    
    // 筛选
    let filtered = mockData.services;
    if (typeFilter) {
        filtered = filtered.filter(s => s.type === typeFilter);
    }
    
    // 排序
    filtered = [...filtered]; // 创建副本避免修改原数织
    if (sortMethod === 'distance') {
        filtered.sort((a, b) => parseFloat(a.distance) - parseFloat(b.distance));
    } else if (sortMethod === 'rating') {
        filtered.sort((a, b) => b.rating - a.rating);
    } else if (sortMethod === 'price') {
        // 按价格排序（取第一个服务项目的价格）
        filtered.sort((a, b) => {
            const priceA = parseInt(a.services[0].price.match(/\d+/)[0]);
            const priceB = parseInt(b.services[0].price.match(/\d+/)[0]);
            return priceA - priceB;
        });
    }
    
    return filtered;
}

