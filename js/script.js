// 收藏/取消收藏用户
function toggleFavorite(userId) {
    if (!currentUser) {
        showToast('请先登录', 'error');
        return;
    }
    
    if (favoriteUsers.has(userId)) {
        favoriteUsers.delete(userId);
        showToast('已取消收藏', 'info');
    } else {
        favoriteUsers.add(userId);
        showToast('收藏成功', 'success');
    }
    
    // 保存到本地存储
    StorageManager.save('favoriteUsers', Array.from(favoriteUsers));
    
    // 刷新显示
    const users = mockData.users.filter(u => !blockedUsers.has(u.id));
    displayMatchResults(users);
}

// 屏蔽用户
function blockUser(userId) {
    if (!currentUser) {
        showToast('请先登录', 'error');
        return;
    }
    
    if (confirm('确定要屏蔽该用户吗？屏蔽后将不再显示该用户的信息。')) {
        blockedUsers.add(userId);
        favoriteUsers.delete(userId);
        
        // 保存到本地存储
        StorageManager.save('blockedUsers', Array.from(blockedUsers));
        StorageManager.save('favoriteUsers', Array.from(favoriteUsers));
        
        showToast('已屏蔽该用户', 'success');
        
        // 刷新显示
        const users = mockData.users.filter(u => !blockedUsers.has(u.id));
        displayMatchResults(users);
    }
}

