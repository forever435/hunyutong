function performSearch(keyword, type) {
    SearchHistory.add(keyword);
    document.getElementById('searchHistory').style.display = 'none';
    document.getElementById('hotSearches').style.display = 'none';
    
    const results = [];
    
    // 搜索政策
    if (type === 'all' || type === 'policy') {
        Object.entries(mockData.policies).forEach(([key, policy]) => {
            const region = key.replace(/-/g, ' ');
            if (region.includes(keyword) || 
                policy.childcare.includes(keyword) ||
                policy.marriageLeave.includes(keyword)) {
                results.push({
                    type: 'policy',
                    title: `${region} - 生育政策`,
                    content: policy.childcare,
                    data: { key, policy }
                });
            }
        });
    }
    
    // 搜索服务机构
    if (type === 'all' || type === 'service') {
        mockData.services.forEach(service => {
            if (service.name.includes(keyword) || 
                service.typeName.includes(keyword) ||
                service.address.includes(keyword)) {
                results.push({
                    type: 'service',
                    title: service.name,
                    content: `${service.typeName} - ${service.address} - 评分${service.rating}`,
                    data: service
                });
            }
        });
    }
    
    // 搜索FAQ
    if (type === 'all' || type === 'faq') {
        faqData.forEach(faq => {
            if (faq.question.includes(keyword) || faq.answer.includes(keyword)) {
                results.push({
                    type: 'faq',
                    title: faq.question,
                    content: faq.answer.substring(0, 100) + '...',
                    data: faq
                });
            }
        });
    }
    
    displaySearchResults(results);
}

function displaySearchResults(results) {
    const container = document.getElementById('searchResults');
    
    if (results.length === 0) {
        container.innerHTML = `
            <div style="text-align: center; padding: 3rem; color: #999;">
                <i class="fas fa-search" style="font-size: 3rem; margin-bottom: 1rem;"></i>
                <p>未找到相关结果</p>
            </div>
        `;
        return;
    }
    
    const typeNames = {
        policy: '政策',
        service: '机构',
        faq: '问题'
    };
    
    container.innerHTML = results.map(result => `
        <div class="search-result-item" onclick='handleSearchResultClick(${JSON.stringify(result)})'>
            <h4>
                <i class="fas fa-${result.type === 'policy' ? 'file-alt' : result.type === 'service' ? 'hospital' : 'question-circle'}"></i>
                ${result.title}
                <span class="search-result-type">${typeNames[result.type]}</span>
            </h4>
            <p>${result.content}</p>
        </div>
    `).join('');
}

function handleSearchResultClick(result) {
    document.getElementById('searchModal').classList.remove('show');
    
    if (result.type === 'policy') {
        // 跳转到已婚专区
        document.querySelector('[data-section="married"]').click();
        showToast('已跳转到相关政策', 'success');
    } else if (result.type === 'service') {
        // 跳转到服务机果
        document.querySelector('[data-section="map"]').click();
        showToast('已跳转到服务机构', 'success');
    } else if (result.type === 'faq') {
        // 打开FAQ
        document.getElementById('faqBtn').click();
        showToast('已打开相关问题', 'success');
    }
}

