function calculateReimbursement() {
    const company = document.getElementById('insuranceCompany').value;
    const type = document.getElementById('insuranceType').value;
    const checkupCost = parseFloat(document.getElementById('checkupCost').value) || 0;
    const hospitalCost = parseFloat(document.getElementById('hospitalCost').value) || 0;
    const surgeryCost = parseFloat(document.getElementById('surgeryCost').value) || 0;
    const otherCost = parseFloat(document.getElementById('otherCost').value) || 0;

    if (!company || !type) {
        showToast('请选择保险公司和保险类型', 'error');
        return;
    }

    const totalCost = checkupCost + hospitalCost + surgeryCost + otherCost;
    if (totalCost === 0) {
        showToast('请输入至少一项费用', 'error');
        return;
    }

    const key = `${company}-${type}`;
    const rule = mockData.insuranceRules[key];

    if (!rule) {
        showToast('暂无该保险的报销规则', 'error');
        return;
    }

    showLoading();
    
    setTimeout(() => {
        // 计算各项报销
        const checkupReimbursement = checkupCost * rule.rates.checkup;
        const hospitalReimbursement = hospitalCost * rule.rates.hospital;
        const surgeryReimbursement = surgeryCost * rule.rates.surgery;
        const otherReimbursement = otherCost * rule.rates.other;

        let totalReimbursement = checkupReimbursement + hospitalReimbursement + surgeryReimbursement + otherReimbursement;
        
        // 不超过最高额库
        const isOverLimit = totalReimbursement > rule.maxAmount;
        if (isOverLimit) {
            totalReimbursement = rule.maxAmount;
        }

        displayReimbursementResult(totalCost, totalReimbursement, {
            checkup: checkupReimbursement,
            hospital: hospitalReimbursement,
            surgery: surgeryReimbursement,
            other: otherReimbursement
        }, rule.maxAmount, isOverLimit);
        
        hideLoading();
        showToast('计算完成', 'success');
        
        // 滚动到结果区域
        document.getElementById('reimbursementResult').scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }, 1000);
}

