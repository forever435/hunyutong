function compareSubsidies(subsidiesA, subsidiesB) {
    let html = '';
    const types = ['一孩', '二孩', '三孩'];
    
    types.forEach((type, index) => {
        const subA = subsidiesA[index];
        const subB = subsidiesB[index];
        
        // 安全地提取金额
        let amountA = 0;
        let amountB = 0;
        let displayA = subA.amount;
        let displayB = subB.amount;
        
        if (subA.amount !== '暂无数据') {
            const matchA = subA.amount.match(/\d+/);
            if (matchA) amountA = parseInt(matchA[0]);
        }
        
        if (subB.amount !== '暂无数据') {
            const matchB = subB.amount.match(/\d+/);
            if (matchB) amountB = parseInt(matchB[0]);
        }
        
        // 只有在都有数据时才高人
        const highlightA = (amountA > 0 && amountB > 0 && amountA > amountB) ? 'compare-highlight' : '';
        const highlightB = (amountA > 0 && amountB > 0 && amountB > amountA) ? 'compare-highlight' : '';
        
        html += `
            <tr>
                <td><strong>${type}补贴</strong></td>
                <td class="${highlightA}">${displayA}</td>
                <td class="${highlightB}">${displayB}</td>
            </tr>
        `;
    });
    
    return html;
}

