function initSearch() {
    const searchBtn = document.getElementById('searchBtn');
    const searchModal = document.getElementById('searchModal');
    const closeBtn = searchModal.querySelector('.close');
    const searchInput = document.getElementById('globalSearchInput');
    const clearSearchBtn = document.getElementById('clearSearchBtn');
    const searchTabs = document.querySelectorAll('.search-tab');
    const clearHistoryBtn = document.getElementById('clearHistoryBtn');
    const hotTags = document.querySelectorAll('.hot-tag');
    
    let currentSearchType = 'all';
    
    // 打开搜索
    searchBtn.addEventListener('click', () => {
        searchModal.classList.add('show');
        searchInput.focus();
        displaySearchHistory();
    });
    
    // 关闭搜索
    closeBtn.addEventListener('click', () => {
        searchModal.classList.remove('show');
        searchInput.value = '';
        clearSearchBtn.style.display = 'none';
    });
    
    // 搜索输入
    searchInput.addEventListener('input', function() {
        clearSearchBtn.style.display = this.value ? 'block' : 'none';
        if (this.value.trim()) {
            performSearch(this.value.trim(), currentSearchType);
        } else {
            document.getElementById('searchResults').innerHTML = '';
            document.getElementById('searchHistory').style.display = 'block';
            document.getElementById('hotSearches').style.display = 'block';
        }
    });
    
    // 清空搜索
    clearSearchBtn.addEventListener('click', () => {
        searchInput.value = '';
        clearSearchBtn.style.display = 'none';
        document.getElementById('searchResults').innerHTML = '';
        document.getElementById('searchHistory').style.display = 'block';
        document.getElementById('hotSearches').style.display = 'block';
        searchInput.focus();
    });
    
    // 搜索类型切换
    searchTabs.forEach(tab => {
        tab.addEventListener('click', function() {
            searchTabs.forEach(t => t.classList.remove('active'));
            this.classList.add('active');
            currentSearchType = this.dataset.type;
            if (searchInput.value.trim()) {
                performSearch(searchInput.value.trim(), currentSearchType);
            }
        });
    });
    
    // 清空历史
    clearHistoryBtn.addEventListener('click', () => {
        SearchHistory.clear();
        displaySearchHistory();
        showToast('搜索历史已清空', 'success');
    });
    
    // 热门搜索
    hotTags.forEach(tag => {
        tag.addEventListener('click', function() {
            const keyword = this.textContent;
            searchInput.value = keyword;
            performSearch(keyword, currentSearchType);
        });
    });
}

